def _talkers(body):
    """Characters in a scene with actual dialogue: a speaker line followed by
    text that is not just a parenthesised stage direction."""
    segs = re.split(r"(?m)^(\S[^\n:]{0,30}):\s*$", body)
    out = set()
    for name, text in zip(segs[1::2], segs[2::2]):
        t = text.strip()
        if t and not t.startswith(("(", "\uff08")):
            out.add(name.strip())
    return out


def _trim(body, cap=1400, focus=None):
    """A scene short enough prints whole; a long one is cut at a speaker
    boundary once at least two characters have talked. With `focus`, the
    window opens one block before that character's first line instead of at
    the top of the scene. Returns (text, cut)."""
    if len(body) <= cap + 300:
        return body, False
    segs = re.split(r"(?m)^(\S[^\n:]{0,30}):\s*$", body)
    blocks = [(n.strip(), t.strip()) for n, t in zip(segs[1::2], segs[2::2])]
    start = 0
    if focus:
        hit = next((i for i, (n, t) in enumerate(blocks)
                    if n == focus and t and not t.startswith(("(", "\uff08"))), 0)
        start = max(0, hit - 1)
    out, talk, ln = [], set(), 0
    for name, t in blocks[start:]:
        out.append(f"{name}:\n{t}")
        ln += len(t)
        if t and not t.startswith(("(", "\uff08")):
            talk.add(name)
        if ln >= cap and len(talk) >= 2 and (not focus or focus in talk):
            break
    return "\n\n".join(out), True


def samples():
    """Two sample scenes per world, bilingual where the world is Chinese.

    Only scenes where at least two characters actually talk qualify -- a
    movement-only scene or a monologue is not a sample of dialogue. Among
    those, the shortest above a floor is taken from each half of the run;
    where every candidate is long (Russia--Ukraine's institutional scenes),
    the shortest is excerpted at a speaker boundary instead of skipped.
    """
    out = ["% generated -- sample scenes from the rendered screenplays"]
    zh_worlds = {"three_kingdoms", "red_chamber"}
    # a world may name one required speaker per half: Russia--Ukraine samples
    # the two principals, who never share a place, one scene each
    stars = {"russia_ukraine": ("Volodymyr Zelenskyy", "Vladimir Putin")}
    for w, title, _, _, _ in WORLDS:
        en = _scenes(f"runs/screenplays/{w}.en.md")
        zh = _scenes(f"runs/screenplays/{w}.zh.md") if w in zh_worlds else []
        if not en:
            continue
        half = len(en) // 2
        def place(h):
            parts = h.lstrip('# ').split('\u00b7')
            return parts[1].strip() if len(parts) > 1 else ""

        def pick(rng, avoid=None, need=None):
            # a sample should read as people talking: scenes carrying long
            # machine artifacts (hash fingerprints, transfer URIs) are the
            # world's style but not a dialogue sample
            arty = re.compile(r"(?:[0-9A-Fa-f]{2}:){8,}|\w+://\S+")
            c = [(i, h, b) for i, (h, b) in enumerate(en)
                 if rng[0] <= i < rng[1] and len(b) >= 350
                 and len(_talkers(b)) >= 2 and not arty.search(b)
                 and (need is None or need in _talkers(b))]
            # two samples from one world should show two places when they can
            c2 = [x for x in c if place(x[1]) != avoid] if avoid else c
            c = c2 or c
            return min(c, key=lambda x: len(x[2])) if c else None
        need = stars.get(w, (None, None))
        first = pick((0, half), need=need[0])
        second = pick((half, len(en)), avoid=place(first[1]) if first else None,
                      need=need[1])
        picks = [(p, n) for p, n in ((first, need[0]), (second, need[1])) if p]
        out.append(f"\\subsection*{{{title}}}")
        for (i, head, body), need_sp in picks:
            body, cut = _trim(body, focus=need_sp)
            head = head.lstrip('# ') + (" (excerpt)" if cut else "")
            out.append(f"\\paragraph{{{_lx(head)}}}\\mbox{{}}\\\\[2pt]")
            out.append("\\begin{zhblock}\\small\\setlength{\\parskip}{3pt}")
            out.append(_lx(body).replace("\n\n", "\n\\par "))
            if cut:
                out.append("\\par\\textit{[\\,scene continues\\,]}")
            if zh and i < len(zh):
                zbody, zcut = _trim(zh[i][1])
                out.append("\\par\\textcolor{gray}{\\rule{0.3\\textwidth}{0.4pt}}\\par")
                out.append("{\\color{gray} " + _lx(zbody).replace("\n\n", "\n\\par ")
                           + ("\\par\\textit{[\\,\\zh{后续从略}\\,]}" if zcut else "") + "}")
            out.append("\\end{zhblock}")
    return "\n".join(out) + "\n"


def tab_cost():
    """Appendix table: what the mechanism costs, per world."""
    RV = load("review_stats")
    rows = []
    for w, title, _, _, _ in WORLDS:
        v = RV["worlds"][w]
        r = v["expansion"].get("recall")
        d = v["store"]["by_depth"]
        kt = v["keeptext"]
        if not r:
            continue
        qb = "--" if r["q_in_base_pct"] is None else f"{r['q_in_base_pct']}\\%"
        qe = "--" if r["q_in_expanded_pct"] is None else f"{r['q_in_expanded_pct']}\\%"
        rows.append(
            f"{title} & {v['store']['rows']:,} & {r['n']} & "
            f"{r['median_base']:.0f}+{r['median_expanded']:.0f} & "
            f"{r['amplification']}$\\times$ & {qb} & {qe} & "
            f"{d['1']['median_aff']:.0f}$\\to${d['4plus']['median_aff']:.0f} & "
            f"{kt['observable_rewrites']}/{kt['merges']} & "
            f"{kt['median_chars_dropped']:.0f} \\\\")
    return ("% generated\n\\begin{tabular}{lrrlrrrrrr}\n\\toprule\n"
            "& & \\multicolumn{5}{c}{\\emph{recall}} & \\emph{affiliated}"
            " & \\multicolumn{2}{c}{\\emph{keep-shorter}} \\\\\n"
            "\\cmidrule(lr){3-7}\\cmidrule(lr){8-8}\\cmidrule(lr){9-10}\n"
            "World & rows & $n$ & hits+exp. & amp. & q\\,in hits & q\\,in exp."
            " & 1$\\to$4+ own. & seen & chars \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, text in [("numbers", macros()), ("tab_footprint", tab_footprint()),
                       ("tab_structure_main", tab_structure_main()),
                       ("tab_quality", tab_quality()), ("tab_ablation", tab_ablation()),
                       ("tab_structure", tab_structure()), ("tab_actions", tab_actions()),
                       ("tab_screenplays", tab_screenplays()), ("samples", samples()),
                       ("tab_cost", tab_cost())]:
        open(f"{OUT}/{name}.tex", "w", encoding="utf-8").write(text)
        print(f"wrote {OUT}/{name}.tex")


if __name__ == "__main__":
    main()
