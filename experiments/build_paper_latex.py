"""Numbers and tables for the LaTeX draft, written straight from the runs.

The prose of paper/main.tex is edited by hand; everything countable in it
comes from here as a macro or a generated table, so the draft cannot drift
from the data the way a typed number does.

    \\input{numbers}   ->  \\ConsSimNew, \\ConsShPct, ...
    \\input{tab_footprint}, tab_quality, tab_ablation, tab_scenarios

Run: venv/bin/python -m experiments.build_paper_latex
"""
