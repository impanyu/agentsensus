def load(p):
    return json.load(open(f"runs/{p}.json", encoding="utf-8"))


def macros():
    """\\newcommand for every number the prose quotes."""
    S = {w: load(f"paper_stats_{tag}") for w, _, tag, _, _ in WORLDS}
    Q = {w: load(res) for w, _, _, res, _ in WORLDS}
    A = load("ablation_results")
    out = ["% generated by experiments/build_paper_latex.py -- do not edit"]

    def cmd(name, value):
        out.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    tk = S["three_kingdoms"]["consensus"]
    cmd("ConsSimNew", tk["sim_new"]); cmd("ConsShPct", f"{tk['sh_pct']}\\%")
    cmd("ConsAffPct", f"{tk['aff_pct']}\\%")
    cmd("GaSimNew", S["three_kingdoms"]["generative_agents"]["sim_new"])
    cmd("CoSimNew", S["three_kingdoms"]["collaborative"]["sim_new"])
    sh = sorted(S[w]["consensus"]["sh_pct"] for w, *_ in WORLDS)
    af = sorted(S[w]["consensus"]["aff_pct"] for w, *_ in WORLDS)
    cmd("ShRange", f"{sh[0]}--{sh[-1]}\\%"); cmd("AffRange", f"{af[0]}--{af[-1]}\\%")
    cmd("MaxOwners", max(S[w]["max_owners"] for w, *_ in WORLDS))
    save = sorted(round(100 * (1 - S[w]["consensus"]["sim_new"] /
                               min(S[w][b]["sim_new"] for b in BACKENDS[1:])))
                  for w, *_ in WORLDS)
    cmd("SaveRange", f"{save[0]}--{save[-1]}\\%")

    # ---- quantities the review asked for; see experiments/review_stats.py.
    # Skipped rather than faked when the file is absent, so a partial rebuild
    # still compiles (the prose that uses them is in the discussion).
    RV = load("review_stats") if os.path.exists("runs/review_stats.json") else None
    if RV:
        W = RV["worlds"]
        rc = {k: v["expansion"]["recall"] for k, v in W.items() if v["expansion"].get("recall")}
        amp = sorted(v["amplification"] for v in rc.values())
        cmd("ExpBaseK", RV["base_top_k"])
        cmd("ExpAmpRange", f"{amp[0]}--{amp[-1]}$\\times$")
        cmd("ExpAmpMax", f"{amp[-1]}$\\times$")
        big = rc["three_kingdoms"]
        cmd("ExpTkTotal", f"{big['median_total']:.0f}")
        cmd("ExpTkAdded", f"{big['median_expanded']:.0f}")
        cmd("ExpRuAmp", f"{rc['russia_ukraine']['amplification']}$\\times$")
        cmd("ExpQBase", f"{big['q_in_base_pct']}--"
                        f"{rc['red_chamber']['q_in_base_pct']}\\%")
        cmd("ExpQAdded", f"{big['q_in_expanded_pct']}\\%")
        kt = {k: v["keeptext"] for k, v in W.items()}
        drop = sorted(v["median_chars_dropped"] for v in kt.values())
        cmd("KeepDropRange", f"{drop[0]:.0f}--{drop[-1]:.0f}")
        cmd("KeepSeen", sum(v["observable_rewrites"] for v in kt.values()))
        cmd("KeepMerges", sum(v["merges"] for v in kt.values()))
        d = W["red_chamber"]["store"]["by_depth"]
        cmd("AffRcLow", f"{d['1']['median_aff']:.0f}")
        cmd("AffRcHigh", f"{d['4plus']['median_aff']:.0f}")
        cmd("LenRcLow", f"{d['1']['median_len']:.0f}")
        cmd("LenRcHigh", f"{d['4plus']['median_len']:.0f}")
        cmd("StoreRowsMax", f"{max(v['store']['rows'] for v in W.values()):,}")
        hr = {m: max(v["headroom"][m]["spread"] for v in W.values() if v["headroom"])
              for m in ("grnd", "traj", "narr", "goal")}
        cmd("SpreadGoal", f"{hr['goal']:.2f}"); cmd("SpreadTraj", f"{hr['traj']:.2f}")
        cmd("SpreadNarr", f"{hr['narr']:.2f}")
        head = {m: min(v["headroom"][m]["headroom_pct"] for v in W.values() if v["headroom"])
                for m in ("goal", "traj", "narr")}
        cmd("HeadGoal", f"{head['goal']}\\%"); cmd("HeadNarr", f"{head['narr']}\\%")

    goals = [Q[w][b]["agg"]["goal"]["mean"] for w, *_ in WORLDS for b in BACKENDS]
    cmd("GoalLo", f"{min(goals):.2f}"); cmd("GoalHi", f"{max(goals):.2f}")
    leads = sum(1 for w, *_ in WORLDS for k in ("grnd", "traj", "narr", "goal")
                if max(Q[w], key=lambda b: Q[w][b]["agg"][k]["mean"]) == "consensus")
    cmd("QualityLeads", leads); cmd("QualityCells", 4 * len(WORLDS))

    fp = {c: json.load(open(f"runs/abl_{c}/result.json", encoding="utf-8"))["footprint"]
          for c in A}
    cmd("AblOnEntries", f"{fp['on_fifo']['entries']:,}")
    cmd("AblOffEntries", f"{fp['off_fifo']['entries']:,}")
    cmd("AblFactor", f"{fp['off_fifo']['entries'] / fp['on_fifo']['entries']:.1f}")
    cmd("AblOffAff", f"{A['off_fifo']['aff_pct']}\\%")
    cmd("AblOnAff", f"{A['on_fifo']['aff_pct']}\\%")
    gpct = [b["goalless_pct"] for w in load("goal_stack_stats").values() for b in w.values()]
    cmd("GoallessLo", f"{min(gpct):.1f}\\%"); cmd("GoallessHi", f"{max(gpct):.1f}\\%")
    return "\n".join(out) + "\n"


def tab_footprint():
    """Table 1, matching the HTML paper: sediment / sim / total per backend,
    grouped by world. Sediment is each mechanism's own ingest of the identical
    source events; sim is what the run added, the comparison the fairness
    protocol licenses; structure lives in the figure, not here."""
    # source-event counts as in Appendix A.3 (Three Kingdoms ingests one
    # event pair merged at sedimentation, hence 6,052 events / 6,051 rows)
    META = {"three_kingdoms": ("fiction, 80 rounds", "g80", 6052),
            "red_chamber": ("fiction, 80 rounds", "rc80", 6506),
            "russia_ukraine": ("real world, 40 rounds", "ru40", 1533),
            "hamlet": ("fiction, 40 rounds", "hl40", 1135)}
    rows = []
    for w, title, tag, _, _ in WORLDS:
        S = load(f"paper_stats_{tag}")
        note, pref, src = META[w]
        for b in BACKENDS:
            total = json.load(open(f"runs/{pref}_{b}/result.json",
                                   encoding="utf-8"))["footprint"]["entries"]
            sed = total - S[b]["sim_new"]
            if b == "consensus":
                rows.append(f"\\multicolumn{{4}}{{l}}{{\\emph{{{title} --- {note}, "
                            f"{src:,} source events}}}} \\\\")
            fmt = (lambda v: f"\\textbf{{{v:,}}}") if b == "consensus" else (lambda v: f"{v:,}")
            rows.append(f"\\quad {LBL[b]} & {fmt(sed)} & {fmt(S[b]['sim_new'])} & "
                        f"{total:,} \\\\")
        rows.append("\\midrule")
    return ("% generated\n\\begin{tabular}{lrrr}\n\\toprule\n"
            "Backend & Sediment & Sim & Total \\\\\n\\midrule\n"
            + "\n".join(rows[:-1]) + "\n\\bottomrule\n\\end{tabular}\n")


