"""Numbers and tables for the LaTeX draft, written straight from the runs.

The prose of paper/main.tex is edited by hand; everything countable in it
comes from here as a macro or a generated table, so the draft cannot drift
from the data the way a typed number does.

    \\input{numbers}   ->  \\ConsSimNew, \\ConsShPct, ...
    \\input{tab_footprint}, tab_quality, tab_ablation, tab_scenarios

Run: venv/bin/python -m experiments.build_paper_latex
"""
import json
import os
import sys

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); sys.path.insert(0, ".")

OUT = "paper"
BACKENDS = ["consensus", "generative_agents", "g_memory", "collaborative"]
LBL = {"consensus": "Consensus", "generative_agents": "Gen.\\ Agents",
       "g_memory": "G-Memory", "collaborative": "Collaborative"}
WORLDS = [("three_kingdoms", "Three Kingdoms", "g80", "results_g80", 80),
          ("red_chamber", "Red Chamber", "rc80", "results_rc80", 80),
          ("russia_ukraine", "Russia--Ukraine", "ru40", "results_ru40", 40),
          ("hamlet", "Hamlet", "hl40", "results_hl40", 40)]
SIM_SRC = {"runtime", "act_on"}


def load(p):
    return json.load(open(f"runs/{p}.json", encoding="utf-8"))


def macros():
    """\\newcommand for every number the prose quotes."""
    S = {w: load(f"paper_stats_{tag}") for w, _, tag, _, _ in WORLDS}
    Q = {w: load(res) for w, _, _, res, _ in WORLDS}
    A = load("ablation_results")
    out = ["% generated by experiments/build_paper_latex.py -- do not edit"]

    def cmd(name, value):
        out.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    tk = S["three_kingdoms"]["consensus"]
    cmd("ConsSimNew", tk["sim_new"]); cmd("ConsShPct", f"{tk['sh_pct']}\\%")
    cmd("ConsAffPct", f"{tk['aff_pct']}\\%")
    cmd("GaSimNew", S["three_kingdoms"]["generative_agents"]["sim_new"])
    cmd("CoSimNew", S["three_kingdoms"]["collaborative"]["sim_new"])
    sh = sorted(S[w]["consensus"]["sh_pct"] for w, *_ in WORLDS)
    af = sorted(S[w]["consensus"]["aff_pct"] for w, *_ in WORLDS)
    cmd("ShRange", f"{sh[0]}--{sh[-1]}\\%"); cmd("AffRange", f"{af[0]}--{af[-1]}\\%")
    cmd("MaxOwners", max(S[w]["max_owners"] for w, *_ in WORLDS))
    save = sorted(round(100 * (1 - S[w]["consensus"]["sim_new"] /
                               min(S[w][b]["sim_new"] for b in BACKENDS[1:])))
                  for w, *_ in WORLDS)
    cmd("SaveRange", f"{save[0]}--{save[-1]}\\%")

    goals = [Q[w][b]["agg"]["goal"]["mean"] for w, *_ in WORLDS for b in BACKENDS]
    cmd("GoalLo", f"{min(goals):.2f}"); cmd("GoalHi", f"{max(goals):.2f}")
    leads = sum(1 for w, *_ in WORLDS for k in ("grnd", "traj", "narr", "goal")
                if max(Q[w], key=lambda b: Q[w][b]["agg"][k]["mean"]) == "consensus")
    cmd("QualityLeads", leads); cmd("QualityCells", 4 * len(WORLDS))

    fp = {c: json.load(open(f"runs/abl_{c}/result.json", encoding="utf-8"))["footprint"]
          for c in A}
    cmd("AblOnEntries", f"{fp['on_fifo']['entries']:,}")
    cmd("AblOffEntries", f"{fp['off_fifo']['entries']:,}")
    cmd("AblFactor", f"{fp['off_fifo']['entries'] / fp['on_fifo']['entries']:.1f}")
    cmd("AblOffAff", f"{A['off_fifo']['aff_pct']}\\%")
    cmd("AblOnAff", f"{A['on_fifo']['aff_pct']}\\%")
    gpct = [b["goalless_pct"] for w in load("goal_stack_stats").values() for b in w.values()]
    cmd("GoallessLo", f"{min(gpct):.1f}\\%"); cmd("GoallessHi", f"{max(gpct):.1f}\\%")
    return "\n".join(out) + "\n"


def tab_footprint():
    S = {w: load(f"paper_stats_{tag}") for w, _, tag, _, _ in WORLDS}
    rows = []
    for w, title, _, _, rounds in WORLDS:
        for i, b in enumerate(BACKENDS):
            s = S[w][b]
            first = f"\\multirow{{4}}{{*}}{{{title} ({rounds}r)}}" if i == 0 else ""
            bold = "\\textbf" if b == "consensus" else "{}"
            rows.append(f"{first} & {LBL[b]} & {bold}{{{s['sim_new']}}} & "
                        f"{s['sh_pct']}\\% & {s['aff_pct']}\\% \\\\")
        rows.append("\\midrule")
    return ("% generated\n\\begin{tabular}{llrrr}\n\\toprule\n"
            "World & Backend & Sim entries & Shared & Linked \\\\\n\\midrule\n"
            + "\n".join(rows[:-1]) + "\n\\bottomrule\n\\end{tabular}\n")


def tab_quality():
    Q = {w: load(res) for w, _, _, res, _ in WORLDS}
    rows = []
    for w, title, _, _, _ in WORLDS:
        for i, b in enumerate(BACKENDS):
            a = Q[w][b]["agg"]
            first = f"\\multirow{{4}}{{*}}{{{title}}}" if i == 0 else ""
            cells = " & ".join(
                f"{a[k]['mean']:.2f}" + ("" if a[k]["std"] == 0 else f"\\tiny$\\pm${a[k]['std']:.2f}")
                for k in ("grnd", "traj", "narr", "goal"))
            rows.append(f"{first} & {LBL[b]} & {cells} \\\\")
        rows.append("\\midrule")
    return ("% generated\n\\begin{tabular}{llrrrr}\n\\toprule\n"
            "World & Backend & Grounding & Trajectory & Narrative & Goal \\\\\n\\midrule\n"
            + "\n".join(rows[:-1]) + "\n\\bottomrule\n\\end{tabular}\n")


def tab_ablation():
    A = load("ablation_results")
    order = [("on_fifo", "on", "fifo \\emph{(published)}"), ("on_relevance", "on", "relevance"),
             ("on_hybrid", "on", "hybrid"), ("off_fifo", "\\textbf{off}", "fifo")]
    rows = []
    for c, m, k in order:
        v = A[c]
        fp = json.load(open(f"runs/abl_{c}/result.json", encoding="utf-8"))["footprint"]
        q = " & ".join(f"{v[f'{x}_m']:.2f}" for x in ("grnd", "traj", "narr", "goal")) \
            if "grnd_m" in v else " & ".join(["--"] * 4)
        rows.append(f"{m} & {k} & {fp['entries']:,} & {v['sim_new']} & {v['sh_pct']}\\% & "
                    f"{v['aff_pct']}\\% & {q} \\\\")
    return ("% generated\n\\begin{tabular}{llrrrrrrrr}\n\\toprule\n"
            "Merge & Cache & Store & Sim & Shared & Linked & Grnd & Traj & Narr & Goal \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def tab_structure():
    """Table A1: merge depth, graph density and what expansion returns."""
    rows = []
    for w, title, tag, _, rounds in WORLDS:
        S = load(f"paper_stats_{tag}")
        c, ae = S["consensus"], S["auto_expand"]
        sh = round(c["sim_new"] * c["sh_pct"] / 100)
        per = ae["items"] / max(ae["with_expansion"], 1)
        rows.append(f"{title} ({rounds}r) & {c['sim_new']} & {sh} ({c['sh_pct']}\\%) & "
                    f"{S['n_3plus']} & {S['max_owners']} & {c['aff_pct']}\\% & "
                    f"{ae['with_expansion']}/{ae['recalls']} & {per:.0f} \\\\")
    return ("% generated\n\\begin{tabular}{lrrrrrrr}\n\\toprule\n"
            "World & Sim entries & Shared & 3+ & Max & Linked & Expanded & Linked/call \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


ACTS = ["say", "read_thread", "observe", "move", "act_on", "read", "think",
        "conclude", "push_goal", "pop_goal", "replace_goal", "update_status",
        "remember", "recall", "wait"]
NEVER = ["gesture", "forget", "revise_memory", "add_affiliated",
         "remove_affiliated", "set_affiliated", "get_affiliated"]


def tab_actions():
    """Table A2: every action every backend called, per world."""
    cache = load("derived_tables")["actions"]
    rows = []
    for w, title, tag, _, _ in WORLDS:
        per = cache.get(tag, {})
        rows.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{title}}}}} \\\\")
        for a in ACTS:
            vals = [per.get(b, {}).get(a, 0) for b in BACKENDS]
            if not sum(vals):
                continue
            rows.append(f"\\quad\\texttt{{{a.replace('_', chr(92) + '_')}}} & "
                        + " & ".join(str(v) for v in vals) + " \\\\")
        rows.append("\\midrule")
    head = " & ".join(LBL[b] for b in BACKENDS)
    return ("% generated\n\\begin{tabular}{lrrrr}\n\\toprule\n"
            f"Action & {head} \\\\\n\\midrule\n"
            + "\n".join(rows[:-1]) + "\n\\bottomrule\n\\end{tabular}\n")


def _lx(t):
    """Escape LaTeX specials in screenplay text."""
    for a, b in [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"),
                 ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"),
                 ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")]:
        t = t.replace(a, b)
    return t


def _scenes(path):
    import re
    if not os.path.exists(path):
        return []
    text = open(path, encoding="utf-8").read()
    parts = re.split(r"(?m)^## ", text)
    return [("## " + p.split("\n", 1)[0].strip(), p.split("\n", 1)[1].strip())
            for p in parts[1:]]


def tab_screenplays():
    """Table: the four screenplays' geometry, from the derived cache."""
    st = load("derived_tables")["screenplay"]
    rows = []
    langs = {"three_kingdoms": True, "red_chamber": True}
    for w, title, _, _, _ in WORLDS:
        v = st[w]
        def chars(lang):
            p = f"runs/screenplays/{w}.{lang}.md"
            return (f"{len(open(p, encoding='utf-8').read()) // 1000}k"
                    if os.path.exists(p) else "--")
        src = f"{chars('zh')} (zh)" if w in langs else "-- (en)"
        rows.append(f"{title} & {v['rounds'][0]}--{v['rounds'][1]} & {v['scenes']} & "
                    f"{v['beats']} & {v['speakers']} & {v['places']} & "
                    f"{chars('en')} & {src} \\\\")
    return ("% generated\n\\begin{tabular}{lrrrrrrr}\n\\toprule\n"
            "World & Rounds & Scenes & Beats & Speakers & Places & English & Source lang. \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def samples():
    """Two sample scenes per world, bilingual where the world is Chinese.

    Chosen by length: the shortest scenes above a floor, one from each half of
    the run, so the samples read whole rather than excerpted.
    """
    out = ["% generated -- sample scenes from the rendered screenplays"]
    zh_worlds = {"three_kingdoms", "red_chamber"}
    for w, title, _, _, _ in WORLDS:
        en = _scenes(f"runs/screenplays/{w}.en.md")
        zh = _scenes(f"runs/screenplays/{w}.zh.md") if w in zh_worlds else []
        if not en:
            continue
        half = len(en) // 2
        def pick(rng):
            c = [(i, h, b) for i, (h, b) in enumerate(en) if rng[0] <= i < rng[1]
                 and 350 <= len(b) <= 1400]
            return min(c, key=lambda x: len(x[2])) if c else None
        picks = [p for p in (pick((0, half)), pick((half, len(en)))) if p]
        out.append(f"\\subsection*{{{title}}}")
        for i, head, body in picks:
            out.append(f"\\paragraph{{{_lx(head.lstrip('# '))}}}\\mbox{{}}\\\\[2pt]")
            out.append("\\begin{zhblock}\\small\\setlength{\\parskip}{3pt}")
            out.append(_lx(body).replace("\n\n", "\n\\par "))
            if zh and i < len(zh):
                out.append("\\par\\textcolor{gray}{\\rule{0.3\\textwidth}{0.4pt}}\\par")
                out.append("\\textcolor{gray}{" + _lx(zh[i][1]).replace("\n\n", "\n\\par ") + "}")
            out.append("\\end{zhblock}")
    return "\n".join(out) + "\n"


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, text in [("numbers", macros()), ("tab_footprint", tab_footprint()),
                       ("tab_quality", tab_quality()), ("tab_ablation", tab_ablation()),
                       ("tab_structure", tab_structure()), ("tab_actions", tab_actions()),
                       ("tab_screenplays", tab_screenplays()), ("samples", samples())]:
        open(f"{OUT}/{name}.tex", "w", encoding="utf-8").write(text)
        print(f"wrote {OUT}/{name}.tex")


if __name__ == "__main__":
    main()
